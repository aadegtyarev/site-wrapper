export function text(language, key) {
  return messages[language]?.[key] || messages.en[key] || key;
}

export function validateDraft(draft, newPassword, confirmation, firstSetup) {
  const errors = {};
  try {
    const url = new URL(draft.url);
    if (!["http:", "https:"].includes(url.protocol) || !url.hostname || url.username || url.password) errors.url = "invalidUrl";
  } catch {
    errors.url = "invalidUrl";
  }
  if (!Number.isInteger(draft.zoom_percent) || draft.zoom_percent < 30 || draft.zoom_percent > 500) errors.zoom_percent = "invalidZoom";
  if (firstSetup && !newPassword) errors.new_password = "passwordRequired";
  else if (newPassword && newPassword.length < 12) errors.new_password = "passwordShort";
  if (newPassword !== confirmation) errors.confirm_password = "passwordMismatch";
  return errors;
}
